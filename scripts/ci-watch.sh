#!/usr/bin/env bash
# ci-watch.sh — poll origin/main and run the bupha shell-runner CI pipeline
# on new commits.
#
# A trigger, not a CI server: no UI, no state beyond the last-seen sha.
# (For pushes instead of polling, `bupha watch` + bupha.toml does the same
# thing off the GitHub webhook.) Run it anywhere that has the bupha CLI
# and the rust toolchain — the pipeline is plain `scripts/ci.sh`, no
# docker. Logs append to $CI_LOG_FILE.
#
#   scripts/ci-watch.sh                  # poll every 60 s
#   CI_JOBS=2 ./scripts/ci-watch.sh
#   HANDL_TOKEN=... ./scripts/ci-watch.sh   # needed while deps are private
#   CI_POST_STATUS=1 ./scripts/ci-watch.sh  # also post GitHub commit statuses
#
# Env:
#   CI_INTERVAL     seconds between polls            (default 60)
#   CI_JOBS         nextest -j / libtest threads     (default 2 — the suite
#                   is memory-bound; do not raise on an 11 GiB box)
#   CI_SHARDS       nextest partitions, serial       (default 1)
#   CI_DOGFOOD_JOBS HNL_DOGFOOD_JOBS inside dogfood  (default 2 — nproc OOMs)
#   CI_TARGET_DIR   shared cargo target dir for the worktree runs
#                   (default <workspace>/.ci-target/host)
#   HANDL_TOKEN     GitHub token for private git deps
#   CI_POST_STATUS  1 = POST commit status via `gh api`
#   CI_LOG_FILE     append target                    (default ci-watch.log
#                   next to this repo)
#   CI_ONCE         1 = run once for current origin/main, then exit
set -uo pipefail

REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"
INTERVAL="${CI_INTERVAL:-60}"
POST_STATUS="${CI_POST_STATUS:-0}"
LOG_FILE="${CI_LOG_FILE:-$REPO_DIR/../ci-watch.log}"
# Worktrees land at $WORKTREE_BASE-<sha12>. The base MUST stay outside the
# workspace root: Cargo.toml self-patches ../host and scripts/ci.sh
# rebuilds the sibling layout as symlinks next to the worktree.
WORKTREE_BASE="${CI_WORKTREE_BASE:-$HOME/dagger/worktrees/ci-watch}"
BUPHA_CFG="${CI_BUPHA_CONFIG:-$REPO_DIR/../ci-watch.bupha.toml}"

log() { printf '[%s] %s\n' "$(date -Is)" "$*" | tee -a "$LOG_FILE"; }

post_status() { # sha state description
  [ "$POST_STATUS" = "1" ] || return 0
  gh api "repos/handl-lang/host/statuses/$1" \
    -f state="$2" -f context="ci/bupha" -f description="$3" \
    --silent 2>/dev/null || log "status post failed ($2 $3)"
}

# Minimal bupha config pointed at the worktree — `bupha run` executes the
# runner's cmd in repo.dir (the worktree), exactly what the watcher does.
write_bupha_config() { # worktree -> path
  cat > "$BUPHA_CFG" <<EOF
# generated by scripts/ci-watch.sh — do not edit, rewritten per run
[[repos]]
name = "handl-lang/host"
dir = "$1"
  [repos.runner]
  kind = "script"
  cmd = "bash scripts/ci.sh ci"

[trigger]
kind = "github"

[runner]
kind = "script"
cmd = "bash scripts/ci.sh ci"
token_env = "HANDL_TOKEN"

[status]
kind = "none"
EOF
  printf '%s\n' "$BUPHA_CFG"
}

# Optional coverage upload (CI_COVERAGE=1): produces coverage/lcov.info in
# the worktree, then uploads with the codecov uploader if CODECOV_TOKEN is
# set and a `codecov` binary is on PATH (one-time:
# curl -Os https://uploader.codecov.io/latest/linux/codecov).
upload_coverage() {
  [ "${CI_COVERAGE:-0}" = "1" ] || return 0
  local wt="$1" sha="$2"
  log "coverage export ${sha:0:12}"
  (cd "$wt" && bash scripts/ci.sh coverage-report) >>"$LOG_FILE" 2>&1 || {
    log "coverage export failed"; return 1; }
  if [ -n "${CODECOV_TOKEN:-}" ] && command -v codecov >/dev/null; then
    (cd "$wt" && codecov -t "$CODECOV_TOKEN" -f coverage/lcov.info -C "$sha") \
      >>"$LOG_FILE" 2>&1 || log "codecov upload failed"
  else
    log "coverage exported to $wt/coverage (no codecov upload)"
  fi
}

run_ci() {
  local sha="$1" wt="$WORKTREE_BASE-${sha:0:12}" rc=0
  rm -rf "$wt"
  git -C "$REPO_DIR" worktree prune >>"$LOG_FILE" 2>&1
  git -C "$REPO_DIR" worktree add --detach "$wt" "$sha" >>"$LOG_FILE" 2>&1 || {
    log "worktree add failed for $sha"; return 1; }
  post_status "$sha" pending "ci running"
  log "ci start ${sha:0:12}"
  if command -v bupha >/dev/null 2>&1; then
    write_bupha_config "$wt" >/dev/null
    bupha --config "$BUPHA_CFG" run >>"$LOG_FILE" 2>&1 || rc=$?
  else
    log "bupha not on PATH — running scripts/ci.sh directly"
    (cd "$wt" && bash scripts/ci.sh ci) >>"$LOG_FILE" 2>&1 || rc=$?
  fi
  if [ "$rc" -eq 0 ]; then
    log "ci PASS ${sha:0:12}"
    post_status "$sha" success "ci passed"
    upload_coverage "$wt" "$sha"
  else
    log "ci FAIL ${sha:0:12} (exit $rc)"
    post_status "$sha" failure "ci failed"
  fi
  git -C "$REPO_DIR" worktree remove --force "$wt" >>"$LOG_FILE" 2>&1
  return "$rc"
}

last=""
log "watching origin/main (interval ${INTERVAL}s)"
while true; do
  git -C "$REPO_DIR" fetch -q origin main 2>>"$LOG_FILE"
  sha="$(git -C "$REPO_DIR" rev-parse origin/main)"
  if [ "$sha" != "$last" ]; then
    [ -n "$last" ] && log "new commit ${sha:0:12}"
    run_ci "$sha"
    last="$sha"
  fi
  [ "${CI_ONCE:-0}" = "1" ] && exit 0
  sleep "$INTERVAL"
done
