#!/usr/bin/env python3
"""Publish the aggregated ADR index into the `docs/` hub repo (ADR-0129 5.2).

Reads project/docs-split.yaml (+ the repo list) and writes
<org>/docs/ADR-INDEX.md: every repo, the ADRs it owns, and the split
children. The canonical registry stays platform/project/adrs/INDEX.md; this
is the published, cross-repo view.

Run from the platform repo: `python3 scripts/gen-docs-index.py`.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
ORG = ROOT.parent
MANIFEST = ROOT / "project" / "docs-split.yaml"
OUT = ORG / "docs" / "ADR-INDEX.md"

NUM = re.compile(r"^(\d+[a-z]?)")
TITLE = re.compile(r"^#\s+(?:ADR-\d+[a-z]?:\s*)?(.*)")
PHASE = {
    "platform": 0, "python": 1, "c": 2, "stdlib": 3, "otlp": 4, "web": 5,
    "native": 6, "dot": 7, "term": 7, "sexp": 7, "handl": 7, "cli": 8,
    "lsp": 8, "meta": 9, "ffi": 10, "lang": 11, "kit-canonical": 11,
    "docs": 12,
}


def title_of(path: Path) -> str:
    if not path.exists():
        return path.stem
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        m = TITLE.match(line)
        if m:
            return m.group(1).strip()
    return path.stem


def main() -> int:
    data = yaml.safe_load(MANIFEST.read_text())
    repos = data.get("repos") or {}

    out = [
        "# ADR index (published)",
        "",
        "Aggregated across the `handl-lang` repos. The **canonical registry** is",
        "`platform/project/adrs/INDEX.md` (private `platform` repo); this page is",
        "the published cross-repo view. Generated by",
        "`platform/scripts/gen-docs-index.py`.",
        "",
        "An ADR that defines a port, the kernel, or composition stays in",
        "`platform`; a repo-local decision lives in that repo's `project` branch.",
        "",
        "## By repo",
        "",
    ]

    for repo, sections in repos.items():
        adrs = []
        for key, sub in (("adrs", "adrs"), ("adrs_archived", "adrs/archived")):
            for name in (sections or {}).get(key) or []:
                m = NUM.match(name)
                if not m:
                    continue
                # the ADR lives in the owning repo's project worktree
                p = ORG / repo / "project" / sub / name
                adrs.append((m.group(1), sub, name, title_of(p)))

        if not adrs:
            continue
        phase = PHASE.get(repo)
        out.append(f"### `{repo}`" + (f" — ADR-0128 Phase {phase}" if phase else ""))
        out.append("")
        out.append("| # | title | file |")
        out.append("|---|---|---|")
        for num, sub, name, title in sorted(adrs, key=lambda a: a[0].rjust(5, "0")):
            out.append(f"| {num} | {title} | `project/{sub}/{name}` |")
        out.append("")

    splits = data.get("splits") or []
    if splits:
        out += ["## Split children", "", "| # | title | repo | parent |", "|---|---|---|---|"]
        for s in splits:
            parent = s["parent"].split("/", 1)[1]
            for t in s.get("targets") or []:
                if t.get("number"):
                    out.append(
                        f"| {t['number']} | {t['title']} | `{t['repo']}` | `{parent}` |"
                    )
        out.append("")

    locals_ = data.get("local_adrs") or []
    if locals_:
        out += [
            "## Repo-local ADRs",
            "",
            "| # | title | repo | file |",
            "|---|---|---|---|",
        ]
        for a in locals_:
            out.append(
                f"| {a['number']} | {a['title']} | `{a['repo']}` | `{a['file']}` |"
            )
        out.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
